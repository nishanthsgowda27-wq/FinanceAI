CREATE DATABASE IF NOT EXISTS financeai CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE financeai;

CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(191) NOT NULL PRIMARY KEY,
  name VARCHAR(191) NOT NULL,
  email VARCHAR(320) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY users_email_unique (email)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS otp_verifications (
  email VARCHAR(320) NOT NULL,
  purpose VARCHAR(64) NOT NULL,
  otp_code CHAR(6) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (email, purpose)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS pending_registrations (
  email VARCHAR(320) NOT NULL PRIMARY KEY,
  name VARCHAR(191) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  expires_at DATETIME(6) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS financial_profiles (
  user_id VARCHAR(191) NOT NULL PRIMARY KEY,
  profession VARCHAR(191) NOT NULL,
  income_type VARCHAR(64) NOT NULL,
  annual_income DECIMAL(15,2) NOT NULL DEFAULT 0,
  age SMALLINT UNSIGNED NOT NULL,
  tax_regime VARCHAR(16) NOT NULL DEFAULT 'new',
  deductions DECIMAL(15,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT financial_profiles_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS expenses (
  id CHAR(36) NOT NULL PRIMARY KEY,
  user_id VARCHAR(191) NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  category VARCHAR(128) NOT NULL,
  description VARCHAR(500) NOT NULL,
  date DATE NOT NULL,
  payment_method VARCHAR(128) NULL,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT expenses_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  KEY expenses_user_date_idx (user_id, date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS transactions (
  id CHAR(36) NOT NULL PRIMARY KEY,
  user_id VARCHAR(191) NOT NULL,
  type ENUM('income', 'expense') NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  category VARCHAR(128) NOT NULL,
  description VARCHAR(500) NOT NULL,
  date DATE NOT NULL,
  payment_method VARCHAR(128) NULL,
  notes TEXT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT transactions_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  KEY transactions_user_date_idx (user_id, date)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS loans (
  id CHAR(36) NOT NULL PRIMARY KEY,
  user_id VARCHAR(191) NOT NULL,
  email VARCHAR(320) NOT NULL,
  loan_type VARCHAR(128) NOT NULL,
  loan_amount DECIMAL(15,2) NOT NULL,
  interest_rate DECIMAL(8,4) NOT NULL,
  tenure_years DECIMAL(8,2) NOT NULL,
  monthly_emi DECIMAL(15,2) NOT NULL,
  total_interest DECIMAL(15,2) NOT NULL,
  total_payment DECIMAL(15,2) NOT NULL,
  cibil_score SMALLINT UNSIGNED NOT NULL,
  minimum_cibil_score SMALLINT UNSIGNED NOT NULL,
  eligible BOOLEAN NOT NULL DEFAULT FALSE,
  approval_status ENUM('approved', 'requires_review') NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT loans_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  KEY loans_user_created_idx (user_id, created_at)
) ENGINE=InnoDB;
